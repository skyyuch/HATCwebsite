import {routing} from '@/i18n/routing';

/**
 * Treat an empty/whitespace value as "not set" — `??` alone would let
 * `NEXT_PUBLIC_SITE_URL=` through as `''` and `new URL('')` in the locale
 * layout then fails every prerender with an opaque `ERR_INVALID_URL`.
 */
export const siteUrl = (
  process.env.NEXT_PUBLIC_SITE_URL?.trim() || 'http://localhost:3000'
).replace(/\/$/, '');

/**
 * Whether search engines may index this deployment. Build-time only: canonical
 * URLs, `robots.txt` and the per-page robots meta tag are all baked into the
 * static output, so a non-production environment has to be built with
 * `SITE_INDEXABLE=false` (set for local and UAT in `config/env/*.env`).
 *
 * Defaults to indexable so an unconfigured build behaves exactly as before.
 */
export const siteIndexable = process.env.SITE_INDEXABLE !== 'false';

/**
 * Brand share card (Open Graph / Twitter), used by every page that has no
 * image of its own. Generated by `scripts/generate-brand-images.mjs`.
 *
 * Declared here as a plain public asset rather than through Next's
 * `opengraph-image` file convention on purpose: a page that declares its own
 * `openGraph` object **replaces** the parent's, so a file-convention image
 * silently disappears from exactly the pages that set a custom title —
 * `/announcements/[slug]` ended up with a Twitter image but no `og:image`,
 * i.e. no thumbnail on WhatsApp or Facebook. Spread this into both
 * `openGraph.images` and `twitter.images` instead.
 *
 * The URL stays relative; `metadataBase` in the locale layout resolves it
 * against the deployment's own host.
 */
export const SHARE_CARD = {
  url: '/brand/share-card.jpg',
  width: 1200,
  height: 630
} as const;

/** hreflang alternates for a given path (path starts with '/', or ''). */
export function localeAlternates(path = ''): Record<string, string> {
  const languages: Record<string, string> = {};
  for (const locale of routing.locales) {
    languages[locale] = `${siteUrl}/${locale}${path}`;
  }
  languages['x-default'] = `${siteUrl}/${routing.defaultLocale}${path}`;
  return languages;
}
